// Draws the landing page's map preview from OpenStreetMap road data and
// writes it to src/landing/map-roads.ts as plain SVG path strings.
// Run with `npm run map` after changing the gym's location in
// src/content/landing.ts (contact.location). Needs network access.
//
// A drawn map instead of an embedded one: no third-party frame or cookies on
// the home page, nothing to load, and it can be styled to match the site.
// Road data © OpenStreetMap contributors (ODbL); the page credits it.

import { readFile, writeFile } from "node:fs/promises";

const OUTPUT = "src/landing/map-roads.ts";
/** Map size in SVG units. Roughly 1 unit = 2 m on the ground at this scale. */
const WIDTH = 800;
const HEIGHT = 520;
const METRES_PER_UNIT = 2.2;

const content = await readFile("src/content/landing.ts", "utf8");
const lat = Number(content.match(/lat:\s*([\d.]+)/)?.[1]);
const lng = Number(content.match(/lng:\s*([\d.]+)/)?.[1]);
if (!lat || !lng) throw new Error("contact.location not found in landing.ts");

// Web Mercator, in metres, centred on the gym.
const R = 6378137;
const toMetres = (la, ln) => [
  (R * (ln - lng) * Math.PI) / 180,
  -R *
    (Math.log(Math.tan(Math.PI / 4 + (la * Math.PI) / 360)) -
      Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))),
];
// Mercator metres are stretched by 1/cos(lat); undo it so the scale is true.
const stretch = 1 / Math.cos((lat * Math.PI) / 180);
const toUnits = (la, ln) => {
  const [x, y] = toMetres(la, ln);
  return [
    WIDTH / 2 + x / stretch / METRES_PER_UNIT,
    HEIGHT / 2 + y / stretch / METRES_PER_UNIT,
  ];
};

const halfW = (WIDTH / 2) * METRES_PER_UNIT * 1.3;
const halfH = (HEIGHT / 2) * METRES_PER_UNIT * 1.3;
const dLat = (halfH / 111320) * 1;
const dLng = halfW / (111320 * Math.cos((lat * Math.PI) / 180));
const bbox = [lat - dLat, lng - dLng, lat + dLat, lng + dLng]
  .map((n) => n.toFixed(6))
  .join(",");

const query = `[out:json][timeout:60];
(
  way(${bbox})[highway~"^(motorway|trunk|primary|secondary|tertiary|unclassified|residential|living_street|service|track|road)$"];
  way(${bbox})[waterway~"^(river|stream|canal)$"];
  way(${bbox})[natural=water];
  way(${bbox})[railway=rail];
);
out geom;`;

// The public Overpass servers are busy at times; try a mirror before giving up.
const SERVERS = [
  "https://overpass-api.de/api/interpreter",
  "https://overpass.private.coffee/api/interpreter",
  "https://maps.mail.ru/osm/tools/overpass/api/interpreter",
];

async function fetchRoads() {
  for (const server of SERVERS) {
    const response = await fetch(server, {
      method: "POST",
      headers: {
        "Content-Type": "application/x-www-form-urlencoded",
        "User-Agent": "landing-map-preview/1.0",
      },
      body: new URLSearchParams({ data: query }),
    }).catch(() => null);
    if (response?.ok) return response.json();
    console.warn(`${server}: ${response?.status ?? "no response"}`);
  }
  throw new Error("Every Overpass server failed; try again in a minute.");
}

const data = await fetchRoads();

/** Road classes, widest first. */
const KIND = {
  motorway: "major",
  trunk: "major",
  primary: "major",
  secondary: "minor",
  tertiary: "minor",
  unclassified: "minor",
  residential: "minor",
  living_street: "minor",
  road: "minor",
  service: "lane",
  track: "lane",
};

const round = (n) => Math.round(n * 10) / 10;
const lines = [];
for (const way of data.elements) {
  if (!way.geometry?.length) continue;
  const kind = way.tags.highway
    ? KIND[way.tags.highway]
    : way.tags.railway
      ? "rail"
      : "water";
  if (!kind) continue;
  const d = way.geometry
    .map((p, i) => {
      const [x, y] = toUnits(p.lat, p.lon);
      return `${i ? "L" : "M"}${round(x)} ${round(y)}`;
    })
    .join("");
  const name = way.tags.ref || way.tags.name;
  lines.push({ kind, d, ...(kind === "major" && name ? { name } : {}) });
}

const order = ["water", "rail", "lane", "minor", "major"];
lines.sort((a, b) => order.indexOf(a.kind) - order.indexOf(b.kind));

const file = `// Generated by scripts/make-map.mjs from OpenStreetMap data. Do not edit.
// Road data © OpenStreetMap contributors, ODbL.

export type MapLine = {
  kind: "major" | "minor" | "lane" | "rail" | "water";
  d: string;
  name?: string;
};

export const mapSize = { width: ${WIDTH}, height: ${HEIGHT} } as const;

export const mapLines: MapLine[] = ${JSON.stringify(lines, null, 2)};
`;

await writeFile(OUTPUT, file);
const counts = lines.reduce(
  (all, line) => ({ ...all, [line.kind]: (all[line.kind] ?? 0) + 1 }),
  {},
);
console.log(`${OUTPUT}  ${lines.length} lines`, counts);
